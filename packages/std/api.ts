import { pluralize } from "./inflectors";
import {
  BuildJsonObjectField,
  insertValueColumns,
  jsonBuildObject,
  sql,
  updateAssignment,
  valuesRow,
} from "./sql_utils";
import { EndpointStatements } from "./statements";
import type { EndpointStatementsOrFn } from "./statements";
import type { System } from "./system";
import type * as yom from "./yom";
import * as YolmGenApi from "./yolm_gen_api";

/**
 * Builder for a per-app HTTP API mounted at `prefix` on `domain`.
 *
 * Accumulates endpoint definitions (added via {@link get}, {@link post},
 * {@link put}, {@link patch}, {@link delete}, or generated by {@link auto})
 * and emits them as YOM at the end of system generation. Created by the
 * system when registering an app's API; you normally configure it through
 * the app definition rather than constructing it directly.
 */
export class Api {
  #endpoints: yom.ApiEndpoint[] = [];

  constructor(
    public domain: string,
    private system: System,
    public prefix: string,
    public domainAliases: string[] = [],
  ) {}

  /** Registers an additional domain that resolves to this same API. */
  addDomainAlias(alias: string) {
    this.domainAliases.push(alias);
  }

  /**
       Adds a GET endpoint to the system at the provided path.
       */
  get(path: string, helper: GetEndpointHelper) {
    this.#endpoints.push({
      method: "GET",
      path,
      procedure: EndpointStatements.normalizeToArray(helper.procedure),
      query: helper.query,
    });
  }

  #addEndpoint(
    method: yom.EndpointMethod,
    path: string,
    helper: EndpointHelper,
  ) {
    this.#endpoints.push({
      method,
      path,
      body: helper.jsonBodyScalar
        ? { type: "Json", scalar: helper.jsonBodyScalar }
        : helper.textBodyScalar
        ? { type: "Text", scalar: helper.textBodyScalar }
        : helper.bytesBodyScalar
        ? { type: "Bytes", scalar: helper.bytesBodyScalar }
        : helper.blobBody
        ? {
          type: "Blob",
          scalar: helper.blobBody.scalar,
          sourceHashScalar: helper.blobBody.sourceHashScalar,
          sizeScalar: helper.blobBody.sizeScalar,
          maxSize: helper.blobBody.maxSize,
          authorize: EndpointStatements.normalizeToArray(
            helper.blobBody.authorize,
          ),
        }
        : undefined,
      procedure: EndpointStatements.normalizeToArray(helper.procedure),
      query: helper.query,
    });
  }

  /** Adds a POST endpoint at `path`. */
  post(path: string, helper: EndpointHelper) {
    this.#addEndpoint("POST", path, helper);
  }

  /** Adds a PUT endpoint at `path`. */
  put(path: string, helper: EndpointHelper) {
    this.#addEndpoint("PUT", path, helper);
  }

  /** Adds a PATCH endpoint at `path`. */
  patch(path: string, helper: EndpointHelper) {
    this.#addEndpoint("PATCH", path, helper);
  }

  /** Adds a DELETE endpoint at `path`. */
  delete(path: string, helper: EndpointHelper) {
    this.#addEndpoint("DELETE", path, helper);
  }

  /** Number of endpoints registered on this API so far. */
  get endpointCount() {
    return this.#endpoints.length;
  }

  /** Whether an endpoint with the given method and exact path is registered. */
  hasEndpoint(method: yom.EndpointMethod, path: string) {
    return this.#endpoints.some((sql) =>
      sql.method === method && sql.path === path
    );
  }

  /**
       Automatically generates restful endpoints for all tables in the system.
       */
  auto(opts: AutoOpts = {}) {
    for (const table of Object.values(this.system.db.tables)) {
      const tableOpts = opts.tables?.[table.name] ?? {};
      if (tableOpts.skip || table.skipAutoApi || table.name !== "contact") {
        continue;
      }
      const urlBase = table.getBaseUrl();
      if (!tableOpts.noDelete) {
        this.delete(`/${urlBase}/{record_id:id}`, {
          procedure: (s) => {
            s.startTransaction();
            s.defScalar(
              "existed",
              sql`exists (select 1 from ${table.identWithDb} where ${table.primaryKeyIdent} = record_id)`,
            );
            s.modify(
              sql`delete from ${table.identWithDb} where ${table.primaryKeyIdent} = record_id`,
            );
            s.commitTransaction();
            s.return(sql`cast(existed as json)`);
          },
        });
      }
      const jsonFields = Object.values(table.fields).map(
        (f) => new BuildJsonObjectField(sql.lit(f.name), f.ident),
      );
      jsonFields.push(
        new BuildJsonObjectField(
          sql.lit(table.primaryKeyFieldName),
          table.primaryKeyIdent,
        ),
      );
      if (tableOpts.relations) {
        for (const relation of tableOpts.relations) {
          const relationOpts = typeof relation === "string"
            ? { otherTable: relation }
            : relation;
          const otherTable = this.system.db.tables[relationOpts.otherTable];
          if (!otherTable) {
            throw new Error(`Table ${relationOpts.otherTable} not found`);
          }
          const foreignKeyField = (relationOpts.foreignKey &&
            otherTable.fields[relationOpts.foreignKey]) ??
            Object.values(otherTable.fields).find(
              (f) => f.type === "ForeignKey" && f.table === table.name,
            );
          if (!foreignKeyField) {
            throw new Error(
              `No foreign key field found for ${table.name} to ${relationOpts.otherTable}`,
            );
          }
          const subJsonFields = [
            new BuildJsonObjectField(
              sql.lit(otherTable.primaryKeyFieldName),
              otherTable.primaryKeyIdent,
            ),
          ];
          if (relationOpts.returnFields) {
            for (const fieldName of relationOpts.returnFields) {
              const field = otherTable.fields[fieldName];
              subJsonFields.push(
                new BuildJsonObjectField(sql.lit(field.name), field.ident),
              );
            }
          } else {
            for (const field of Object.values(otherTable.fields)) {
              if (field === foreignKeyField) {
                continue;
              }
              subJsonFields.push(
                new BuildJsonObjectField(sql.lit(field.name), field.ident),
              );
            }
          }
          jsonFields.push(
            new BuildJsonObjectField(
              sql.lit(pluralize(otherTable.name).replaceAll(" ", "_")),
              sql`(select json_array_agg(${jsonBuildObject(subJsonFields)})
                from ${otherTable.identWithDb}
                where ${otherTable.ident}.${foreignKeyField.ident} = ${table.ident}.${table.primaryKeyIdent})`,
            ),
          );
        }
      }
      if (!tableOpts.noGetRecord) {
        this.get(`/${urlBase}/{record_id:id}`, {
          procedure: (s) => {
            s.if(
              sql`not exists (select 1 from ${table.identWithDb} where ${table.primaryKeyIdent} = record_id)`,
              (s) => {
                s.setHttpStatus(404);
                s.return(sql`cast('null' as json)`);
              },
            );
            s.return(sql`(select ${jsonBuildObject(jsonFields)}
            from ${table.identWithDb}
            where ${table.primaryKeyIdent} = record_id)`);
          },
        });
      }
      if (!tableOpts.noGetList) {
        this.get(`/${urlBase}`, {
          query: [
            { name: "limit", type: { type: "Int" }, default: "25" },
            { name: "offset", type: { type: "Int" }, default: "0" },
          ],
          procedure: (s) =>
            s.return(sql`(select json_array_agg(${jsonBuildObject(jsonFields)})
                from ${table.identWithDb}
                limit limit offset offset)`),
        });
      }
      if (!tableOpts.noPost) {
        const insertNames = Object.values(table.fields).map((f) => f.ident);
        const insertValues = valuesRow(
          Object.values(table.fields).map((f) =>
            f.castToType(sql`record_input->>${sql.lit(f.name)}`)
          ),
        );
        this.post(`/${urlBase}`, {
          jsonBodyScalar: "record_input",
          procedure: (s) => {
            s.startTransaction();
            s.modify(
              sql`insert into ${table.identWithDb} ${
                insertValueColumns(
                  ...insertNames,
                )
              } values ${insertValues}`,
            );
            s.defScalar("record_id", sql`last_record_id(${table.identWithDb})`);
            s.commitTransaction();
            s.return(sql`(select ${jsonBuildObject(jsonFields)}
            from ${table.identWithDb}
            where ${table.primaryKeyIdent} = record_id)`);
          },
        });
      }
      if (!tableOpts.noPut) {
        const updateFields = Object.values(table.fields).map((f) =>
          updateAssignment(
            f.ident,
            sql`case when (record_input->>${
              sql.lit(
                f.name,
              )
            }) is not null then cast(record_input->>${sql.lit(f.name)} as ${
              sql(
                f.castType,
              )
            }) end`,
          )
        );
        this.put(`/${urlBase}/{record_id:id}`, {
          jsonBodyScalar: "record_input",
          procedure: (s) => {
            s.startTransaction();
            s.modify(
              sql`update ${table.identWithDb} set ${updateFields} where ${table.primaryKeyIdent} = record_id`,
            );
            s.commitTransaction();
            s.return(sql`(select ${jsonBuildObject(jsonFields)}
            from ${table.identWithDb}
            where ${table.primaryKeyIdent} = record_id)`);
          },
        });
      }
    }
  }

  /** Serializes this API and its endpoints to YOM. */
  generateYom(): yom.Api {
    return {
      domain: this.domain,
      prefix: this.prefix,
      domainAliases: this.domainAliases,
      endpoints: this.#endpoints,
    };
  }

  /**
   * Registers this API and its endpoints directly through the Yolm
   * generation ops (the newer codegen path), rather than returning a YOM
   * object via {@link generateYom}.
   */
  generateYom2() {
    const apiIndex = YolmGenApi.addApi(
      this.domain,
      this.prefix,
      this.domainAliases,
    );
    for (const endpoint of this.#endpoints) {
      YolmGenApi.addApiEndpoint(apiIndex, endpoint);
    }
  }
}

/** Options for {@link Api.auto}; per-table overrides keyed by table name. */
export interface AutoOpts {
  tables?: Record<string, AutoTableOpts>;
}

/** Per-table overrides for {@link Api.auto} REST endpoint generation. */
export interface AutoTableOpts {
  /** Skip this table entirely (generate no endpoints for it). */
  skip?: boolean;
  /** Omit the `DELETE /{record}` endpoint. */
  noDelete?: boolean;
  /** Omit the `POST /` (create) endpoint. */
  noPost?: boolean;
  /** Omit the `PUT /{record}` (update) endpoint. */
  noPut?: boolean;
  /** Omit the `GET /{record}` (single record) endpoint. */
  noGetRecord?: boolean;
  /** Omit the `GET /` (list) endpoint. */
  noGetList?: boolean;
  /** Related tables to embed as nested arrays in the JSON responses. */
  relations?: (string | AutoRelationOpts)[];
}

/** Describes a related table to embed in {@link Api.auto} responses. */
export interface AutoRelationOpts {
  /** Name of the related table to embed. */
  otherTable: string;
  /**
   * Foreign-key field on `otherTable` pointing back at the parent. If
   * omitted, the first `ForeignKey` field referencing the parent is used.
   */
  foreignKey?: string;
  /** Fields of `otherTable` to include; defaults to all but the foreign key. */
  returnFields?: string[];
}

/** Endpoint configuration for {@link Api.get} / {@link GlobalApi.get}. */
export interface GetEndpointHelper {
  /** Query-string parameters accepted by the endpoint. */
  query?: yom.QueryParam[];
  /** Procedure run to produce the response. */
  procedure: EndpointStatementsOrFn;
}

/**
 * Endpoint configuration for body-carrying methods (POST/PUT/PATCH/DELETE).
 * At most one body scalar should be set; it names the procedure scalar the
 * request body is decoded into.
 */
export interface EndpointHelper {
  /** Query-string parameters accepted by the endpoint. */
  query?: yom.QueryParam[];
  /** Scalar name to receive the request body parsed as JSON. */
  jsonBodyScalar?: string;
  /** Scalar name to receive the raw request body as text. */
  textBodyScalar?: string;
  /** Scalar name to receive the raw request body as bytes. */
  bytesBodyScalar?: string;
  /**
   * Large-file upload body. The platform stores the upload as a blob before
   * the procedure runs; the procedure receives the 32-byte blob hash (and
   * optionally the size), never the raw bytes. Uploads above the single
   * request limit use the built-in chunked protocol under
   * `<prefix>/_blob-upload/`.
   */
  blobBody?: BlobBodyHelper;
  /** Procedure run to produce the response. */
  procedure: EndpointStatementsOrFn;
}

/** Configuration for {@link EndpointHelper.blobBody}. */
export interface BlobBodyHelper {
  /** BLAKE3 hash of encrypt(compress(source bytes)). */
  scalar: string;
  /** BLAKE3 of the exact source bytes before compression and encryption. */
  sourceHashScalar?: string;
  /** Optional scalar receiving the upload content size in bytes. */
  sizeScalar?: string;
  /** Maximum accepted upload size in bytes (platform default 1 GiB). */
  maxSize?: number;
  /**
   * Runs before any upload bytes are accepted (and again before the main
   * procedure). Reject by setting an HTTP status >= 400 or returning a
   * non-null value; falling off the end allows the upload.
   */
  authorize: EndpointStatementsOrFn;
}

/**
 * Builder for the system-wide (cross-app) HTTP API. Mirrors {@link Api}'s
 * endpoint methods but is not scoped to a single app domain.
 */
export class GlobalApi {
  #endpoints: yom.ApiEndpoint[] = [];

  /**
       Adds a GET endpoint to the system at the provided path.
       */
  get(path: string, helper: GetEndpointHelper) {
    this.#endpoints.push({
      method: "GET",
      path,
      procedure: EndpointStatements.normalizeToArray(helper.procedure),
      query: helper.query,
    });
  }

  #addEndpoint(
    method: yom.EndpointMethod,
    path: string,
    helper: EndpointHelper,
  ) {
    this.#endpoints.push({
      method,
      path,
      body: helper.jsonBodyScalar
        ? { type: "Json", scalar: helper.jsonBodyScalar }
        : helper.textBodyScalar
        ? { type: "Text", scalar: helper.textBodyScalar }
        : helper.bytesBodyScalar
        ? { type: "Bytes", scalar: helper.bytesBodyScalar }
        : helper.blobBody
        ? {
          type: "Blob",
          scalar: helper.blobBody.scalar,
          sourceHashScalar: helper.blobBody.sourceHashScalar,
          sizeScalar: helper.blobBody.sizeScalar,
          maxSize: helper.blobBody.maxSize,
          authorize: EndpointStatements.normalizeToArray(
            helper.blobBody.authorize,
          ),
        }
        : undefined,
      procedure: EndpointStatements.normalizeToArray(helper.procedure),
      query: helper.query,
    });
  }

  /** Adds a POST endpoint at `path`. */
  post(path: string, helper: EndpointHelper) {
    this.#addEndpoint("POST", path, helper);
  }

  /** Adds a PUT endpoint at `path`. */
  put(path: string, helper: EndpointHelper) {
    this.#addEndpoint("PUT", path, helper);
  }

  /** Adds a PATCH endpoint at `path`. */
  patch(path: string, helper: EndpointHelper) {
    this.#addEndpoint("PATCH", path, helper);
  }

  /** Adds a DELETE endpoint at `path`. */
  delete(path: string, helper: EndpointHelper) {
    this.#addEndpoint("DELETE", path, helper);
  }

  /** Number of endpoints registered on this API so far. */
  get endpointCount() {
    return this.#endpoints.length;
  }

  /** Whether an endpoint with the given method and exact path is registered. */
  hasEndpoint(method: yom.EndpointMethod, path: string) {
    return this.#endpoints.some((sql) =>
      sql.method === method && sql.path === path
    );
  }

  /** Returns the accumulated endpoint definitions. */
  getEndpoints(): yom.ApiEndpoint[] {
    return this.#endpoints;
  }

  /** Serializes the registered endpoints to YOM. */
  generateYom(): yom.ApiEndpoint[] {
    return this.#endpoints;
  }
}
